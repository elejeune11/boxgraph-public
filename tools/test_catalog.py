"""Generate docs/TESTS.md: every test, what it checks, and the design rule behind it.

  python tools/test_catalog.py          write docs/TESTS.md
  python tools/test_catalog.py --check  exit 1 if docs/TESTS.md is out of date

The catalogue is built from the test files themselves (module docstrings,
test names, test docstrings, parametrize cases), so it cannot drift from them.
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TESTS = ROOT / "tests"
OUT = ROOT / "docs" / "TESTS.md"

AREAS = {
    "test_precision.py": "Verdicts at printed precision",
    "test_rounding.py": "Verdicts that carry the rounding of printed inputs",
    "test_variants.py": "Corrected variants of misprinted equations",
    "test_units.py": "Units and quantities",
    "test_engine.py": "Building one record",
    "test_validate.py": "Soundness of a record",
    "test_stochastic.py": "Models with randomness",
    "test_errorbars.py": "Measured data: error bars and bar charts",
    "test_figure_code.py": "Figure readings by the record's own code",
    "test_atlas.py": "ModelAtlas",
    "test_synthesis.py": "The Synthesis",
    "test_validation.py": "Models against other papers' measurements",
    "test_report.py": "The written review",
    "test_explore.py": "The explorer page",
    "test_overview.py": "The overview page",
    "test_cli.py": "Command-line tool",
    "test_ingest.py": "Ingesting a PDF",
    "test_digitize.py": "Reading figures",
    "test_figures.py": "Figure readings in records",
    "test_orchestrator.py": "Running agents in parallel",
    "test_pipeline_jobs.py": "The corpus job graph",
    "test_corpus.py": "Adding papers: the corpus list and the ledger",
    "test_corpora.py": "Several corpora side by side",
    "test_pairs.py": "Which papers are related to which",
    "test_pipeline_e2e.py": "The whole pipeline, end to end",
    "test_sources.py": "Code and data as sources",
    "test_robustness.py": "Mistakes in a record never crash a build",
    "test_experiment_score.py": "Scoring the digitizer comparison",
    "test_docs.py": "Generated documentation",
}


def humanize(name: str) -> str:
    words = name.removeprefix("test_").replace("_", " ")
    return words[:1].upper() + words[1:] + "."


def cases(fn: ast.FunctionDef) -> int:
    n = 1
    for d in fn.decorator_list:
        if isinstance(d, ast.Call) and getattr(d.func, "attr", "") == "parametrize" and len(d.args) >= 2:
            if isinstance(d.args[1], (ast.List, ast.Tuple)):
                n *= len(d.args[1].elts)
    return n


def skip_note(fn: ast.FunctionDef, module_marks: set[str]) -> str:
    names = {getattr(d, "id", "") for d in fn.decorator_list} | module_marks
    return " (needs the corpus PDFs and poppler)" if "needs_pdf" in names else ""


def catalogue() -> str:
    lines = [
        "# Test catalogue",
        "",
        "Generated by `tools/test_catalog.py` from the test files; do not edit by hand.",
        "Run the tests with `make test` (or `pytest`). Each section names the design",
        "document the tests hold the code to.",
        "",
    ]
    total = 0
    rows_by_area = []
    # a fixed order: the named areas first, then any other file by name (never the filesystem's order)
    for f in sorted(TESTS.glob("test_*.py"), key=lambda p: (list(AREAS).index(p.name) if p.name in AREAS else 99, p.name)):
        tree = ast.parse(f.read_text())
        doc = (ast.get_docstring(tree) or "").replace("\n", " ")
        fns = [n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name.startswith("test_")]
        rows = []
        for fn in fns:
            n = cases(fn)
            total += n
            what = (ast.get_docstring(fn) or humanize(fn.name)).replace("\n", " ")
            rows.append(f"| `{fn.name}` | {what}{skip_note(fn, set())} | {n} |")
        rows_by_area.append((f.name, doc, rows, sum(cases(fn) for fn in fns)))
    lines.append(f"**{total} test cases** in {len(rows_by_area)} files.")
    lines.append("")
    lines.append("| Area | File | Cases |")
    lines.append("|---|---|---|")
    for name, _, _, n in rows_by_area:
        lines.append(f"| {AREAS.get(name, name)} | `tests/{name}` | {n} |")
    for name, doc, rows, _n in rows_by_area:
        lines += ["", f"## {AREAS.get(name, name)}", "", f"`tests/{name}`. {doc}", "",
                  "| Test | What it checks | Cases |", "|---|---|---|", *rows]
    lines += ["", "## Fixtures", "",
              "- `tests/fixtures/toy/`: a small hand-written record with a misprint, an added input with",
              "  alternatives, a curve, a refinement that settles and one that keeps moving.",
              "- `tests/fixtures/toy2/`: a second paper stating the same law in other symbols, plus a",
              "  wrong-sign model, a zero-force limit, a first-order approximation, two bare ratios,",
              "  cited values (one miscited) and relations of every kind.",
              ""]
    return "\n".join(lines)


def main() -> int:
    text = catalogue()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/TESTS.md is out of date: run python tools/test_catalog.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
